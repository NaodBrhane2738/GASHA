"""
==============================================================================
FILE: apps/api/app/ai/providers/base.py
ROLE / OWNERSHIP: AI & Security Intelligence Engineers
OBJECTIVE: Abstract base interface for AI model providers in GASHA.
TOOLS & LIBRARIES: Python ABC, Pydantic v2
KEY FEATURES:
  - AIProvider: Abstract base class defining generate_investigation() and health_check().
  - AIProviderStatus: Structured health/availability metrics model.
  - ProviderConfig: Base configuration model for provider adapters.
EXPECTED RESULTS / BEHAVIOR:
  - Decouples GASHA's investigation pipeline from specific LLM engines.
  - Enables pluggable local (Ollama, Ministral, Qwen, DeepSeek) and future adapters.
==============================================================================
"""

from abc import ABC, abstractmethod
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


class AIProviderStatus(BaseModel):
    """Health check status and connectivity metrics for an AI provider."""
    provider: str = Field(..., description="Provider name (e.g. 'ollama')")
    available: bool = Field(..., description="True if provider service is reachable and healthy")
    model: str = Field(..., description="Configured default model name")
    latency_ms: Optional[float] = Field(default=None, description="Health check ping round-trip latency in milliseconds")
    error: Optional[str] = Field(default=None, description="Error message if provider is unavailable")
    version: Optional[str] = Field(default=None, description="Underlying provider service version")

    model_config = ConfigDict(extra="ignore")


class ProviderConfig(BaseModel):
    """Configuration settings for an AI provider instance."""
    provider_name: str = Field(default="ollama", description="Provider identifier")
    base_url: str = Field(default="http://localhost:11434", description="Base HTTP URL for provider API")
    model: str = Field(default="qwen2.5-coder:7b", description="Default model name to request")
    timeout_seconds: float = Field(default=30.0, description="HTTP request timeout in seconds")
    temperature: float = Field(default=0.1, description="Sampling temperature for deterministic reasoning")
    extra_options: Dict[str, Any] = Field(default_factory=dict, description="Provider-specific tuning parameters")

    model_config = ConfigDict(extra="ignore")


class AIProvider(ABC):
    """
    Abstract interface for AI inference providers.
    All local model adapters (Ollama, etc.) must implement this interface.
    """

    def __init__(self, config: Optional[ProviderConfig] = None):
        self.config = config or ProviderConfig()

    @property
    def provider_name(self) -> str:
        """Returns the identifier name of this provider."""
        return self.config.provider_name

    @property
    def default_model(self) -> str:
        """Returns the default model configured for this provider."""
        return self.config.model

    @abstractmethod
    async def generate_investigation(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        model: Optional[str] = None,
        format_json: bool = True,
    ) -> str:
        """
        Executes inference for an investigation prompt and returns raw model text output.

        Args:
            prompt: Formatted user investigation prompt (containing delimited context).
            system_prompt: System instructions establishing boundaries and output schema.
            model: Optional model override. Defaults to self.config.model.
            format_json: If True, instructs provider API to force JSON output mode.

        Returns:
            Raw string generated by the model.

        Raises:
            AIProviderConnectionError: If connection to provider fails.
            AIProviderTimeoutError: If inference times out.
            AIProviderError: For other provider-level failures.
        """
        pass

    @abstractmethod
    async def health_check(self) -> AIProviderStatus:
        """
        Performs a non-blocking health check against the provider API.

        Returns:
            AIProviderStatus detailing availability, latency, and error if any.
        """
        pass


class AIProviderError(Exception):
    """Base exception for AI provider errors."""
    pass


class AIProviderConnectionError(AIProviderError):
    """Raised when connection to the AI provider fails (e.g. service down)."""
    pass


class AIProviderTimeoutError(AIProviderError):
    """Raised when a request to the AI provider exceeds timeout."""
    pass
